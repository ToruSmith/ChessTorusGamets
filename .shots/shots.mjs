import { mkdirSync } from 'node:fs';
import { chromium } from '@playwright/test';
const base = 'http://localhost:4173/';
const start = 'rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1';
const moves = ['e2e4', 'e7e5', 'f1c4', 'b8c6', 'd1h5', 'g8f6', 'h5f7'];
mkdirSync('docs/screenshots', { recursive: true });
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1280, height: 800 }, locale: 'zh-TW', deviceScaleFactor: 1 });
const page = await ctx.newPage();
const shot = (name) => page.screenshot({ path: `docs/screenshots/${name}.jpg`, type: 'jpeg', quality: 82 });
await page.goto(base);
await page.waitForSelector('[data-mode]');
await shot('home');
await page.evaluate(({ start, moves }) => {
  localStorage.setItem('chess.local.v1', JSON.stringify({ version: 1, startFen: start, timeControl: null, moves: moves.slice(0, 6).map((uci, i) => ({ uci, t: 1000 + i })), events: [] }));
  localStorage.setItem('chess.analysis.v1', JSON.stringify({ startFen: start, moves, result: { winner: 'w', reason: 'checkmate', ply: 7 } }));
}, { start, moves });
await page.goto(`${base}#/local`);
await page.waitForSelector('[data-testid=status]');
await page.waitForTimeout(500);
await shot('game');
await page.goto(`${base}#/analysis`);
await page.getByText('分析完成').waitFor({ timeout: 90000 });
await page.waitForTimeout(500);
await shot('analysis');
await page.goto(`${base}#/puzzles`);
await page.waitForSelector('[data-testid=puzzle-status]');
await page.waitForTimeout(500);
await shot('puzzles');
await browser.close();
